"""
Generates firmware/DeskCYD/fonts.h from Figtree (run by the GitHub build).
Each font is stored as 4-bit anti-aliased glyphs in flash, so the CYD can draw
smooth text without any font files of its own.

usage: python make_fonts.py Figtree.ttf out/fonts.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH, OUT = sys.argv[1], sys.argv[2]

# name, pixel size, weight, first char, last char
SPECS = [
    ("F_SMALL", 12, 500, 32, 126),
    ("F_BODY", 15, 500, 32, 126),
    ("F_BODYB", 15, 700, 32, 126),
    ("F_TITLE", 20, 700, 32, 126),
    ("F_LARGE", 30, 600, 32, 126),
    ("F_TEMP", 42, 300, 45, 58),   # '-', '.', '/', digits, ':' for the big temperature
]


def load(size, weight):
    f = ImageFont.truetype(FONT_PATH, size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f


out = [
    "// Generated by tools/make_fonts.py - do not edit",
    "#pragma once",
    "#include <stdint.h>",
    "#ifndef DESKCYD_FONT_TYPES",
    "#define DESKCYD_FONT_TYPES",
    "struct FontGlyph { uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; };",
    "struct AAFont { const uint8_t *bmp; const FontGlyph *g; uint8_t first, last; uint8_t ascent, lineH; };",
    "#endif",
]

for name, size, weight, first, last in SPECS:
    f = load(size, weight)
    ascent, descent = f.getmetrics()
    bmp = bytearray()
    glyphs = []
    for code in range(first, last + 1):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        bbox = f.getbbox(ch)  # anchor 'la': (0,0) is left / ascender line
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if w <= 0 or h <= 0:
            glyphs.append((len(bmp), 0, 0, 0, 0, adv))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=f, fill=255)
        px = img.tobytes()
        off = len(bmp)
        nib = [(p + 8) // 17 for p in px]  # 0..15
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            bmp.append((min(nib[i], 15) << 4) | min(nib[i + 1], 15))
        glyphs.append((off, w, h, bbox[0], bbox[1] - ascent, adv))
    out.append(f"static const uint8_t {name}_bmp[] = {{")
    for i in range(0, len(bmp), 32):
        out.append("  " + ",".join(str(b) for b in bmp[i:i + 32]) + ",")
    out.append("  0};")
    out.append(f"static const FontGlyph {name}_g[] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const AAFont {name} = {{{name}_bmp, {name}_g, {first}, {last}, {ascent}, {ascent + descent}}};")

with open(OUT, "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote", OUT)
