"""
Generates firmware/DeskCYD/mapdata.h: the USA day and night satellite pictures
(NASA Blue Marble + Black Marble), cut to 320 x 240 for the CYD. Run by the GitHub build.

The map is a simple "equirectangular" projection with the longitude squashed by
cos(MID_LAT), so every screen row is one latitude and every column one longitude.
That lets the CYD work out day/night for each pixel very quickly.

usage: python make_map.py day.jpg night.jpg out/mapdata.h [preview_dir]
"""
import math
import os
import sys

from PIL import Image, ImageEnhance

Image.MAX_IMAGE_PIXELS = None

W, H = 320, 240
LON_W, LON_E = -125.5, -65.5          # left / right edge of the screen
MID_LAT = 37.5                        # centre latitude of the screen
PX_PER_DEG_LON = W / (LON_E - LON_W)
PX_PER_DEG_LAT = PX_PER_DEG_LON / math.cos(math.radians(MID_LAT))
LAT_N = MID_LAT + (H / 2) / PX_PER_DEG_LAT
LAT_S = MID_LAT - (H / 2) / PX_PER_DEG_LAT

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def crop_world(path):
    """Cut the map area out of a whole-world (equirectangular) picture and size it to 320x240."""
    img = Image.open(path).convert("RGB")
    iw, ih = img.size
    x0 = (LON_W + 180) / 360 * iw
    x1 = (LON_E + 180) / 360 * iw
    y0 = (90 - LAT_N) / 180 * ih
    y1 = (90 - LAT_S) / 180 * ih
    return img.resize((W, H), Image.LANCZOS, box=(x0, y0, x1, y1))


def to565(img):
    """RGB -> RGB565 with a little ordered dithering (avoids banding in the oceans)."""
    px = img.load()
    out = []
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            d = (BAYER[y & 3][x & 3] / 16.0) - 0.5
            r = min(255, max(0, int(r + d * 8)))
            g = min(255, max(0, int(g + d * 4)))
            b = min(255, max(0, int(b + d * 8)))
            out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def from565(v):
    return (((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31)


def main():
    day_path, night_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    preview_dir = sys.argv[4] if len(sys.argv) > 4 else None

    day = crop_world(day_path)
    day = ImageEnhance.Color(day).enhance(1.12)
    day = ImageEnhance.Contrast(day).enhance(1.06)

    night = crop_world(night_path)
    # Black Marble: keep the land dark and make the city lights glow a bit warmer/brighter
    npx = night.load()
    for y in range(H):
        for x in range(W):
            r, g, b = npx[x, y]
            lum = (r * 3 + g * 6 + b) / 10
            k = 0.55 + 0.9 * min(1.0, lum / 160)   # dim background, boost lights
            npx[x, y] = (min(255, int(r * k * 1.05)), min(255, int(g * k)), min(255, int(b * k * 0.95)))

    d565 = to565(day)
    n565 = to565(night)

    lines = [
        "// Generated by tools/make_map.py - do not edit",
        "// Satellite imagery: NASA Earth Observatory (Blue Marble Next Generation, Black Marble 2016)",
        "#pragma once",
        "#include <stdint.h>",
        f"#define MAP_W {W}",
        f"#define MAP_H {H}",
        f"#define MAP_LON_W ({LON_W}f)",
        f"#define MAP_LAT_N ({LAT_N:.5f}f)",
        f"#define MAP_PX_PER_DEG_LON ({PX_PER_DEG_LON:.6f}f)",
        f"#define MAP_PX_PER_DEG_LAT ({PX_PER_DEG_LAT:.6f}f)",
    ]
    for name, data in (("MAP_DAY", d565), ("MAP_NIGHT", n565)):
        lines.append(f"static const uint16_t {name}[MAP_W * MAP_H] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        lines.append("};")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", out_path, f"lat {LAT_S:.2f}..{LAT_N:.2f}")

    if preview_dir:
        os.makedirs(preview_dir, exist_ok=True)
        for name, data in (("map-day.png", d565), ("map-night.png", n565)):
            im = Image.new("RGB", (W, H))
            im.putdata([from565(v) for v in data])
            im.resize((W * 2, H * 2), Image.NEAREST).save(os.path.join(preview_dir, name))


if __name__ == "__main__":
    main()
